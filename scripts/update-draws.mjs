// Refreshes www/draws.js, the draw history bundled into the app.
// Source: https://github.com/smok95/lotto (a public JSON mirror of the 6/45 results).
// Run weekly by .github/workflows/update-draws.yml, or by hand: node scripts/update-draws.mjs
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCES = [
  'https://smok95.github.io/lotto/results/all.json',
  'https://raw.githubusercontent.com/smok95/lotto/main/results/all.json'
];
const root = fileURLToPath(new URL('..', import.meta.url));
const out = join(root, 'www', 'draws.js');

async function fetchAll() {
  let lastError;
  for (const url of SOURCES) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
      return await res.json();
    } catch (e) { lastError = e; console.warn(String(e)); }
  }
  throw lastError;
}

// Compact row: [draw, 'YYYY-MM-DD', n1..n6, bonus, firstPrize, firstWinners]
function toRow(d) {
  const nums = [...d.numbers].sort((a, b) => a - b);
  const ok = Number.isInteger(d.draw_no) && nums.length === 6 && new Set(nums).size === 6 &&
    [...nums, d.bonus_no].every(n => Number.isInteger(n) && n >= 1 && n <= 45) && !nums.includes(d.bonus_no);
  if (!ok) throw new Error(`bad draw ${JSON.stringify(d)}`);
  const first = (d.divisions && d.divisions[0]) || {};
  return [d.draw_no, String(d.date).slice(0, 10), ...nums, d.bonus_no, first.prize || 0, first.winners || 0];
}

const raw = await fetchAll();
const rows = raw.map(toRow).sort((a, b) => a[0] - b[0]);
rows.forEach((r, i) => { if (r[0] !== i + 1) throw new Error(`draw ${i + 1} missing`); });

const previous = existsSync(out) ? (readFileSync(out, 'utf8').match(/\[(\d+),"/g) || []).length : 0;
if (rows.length < previous) throw new Error(`refusing to shrink history: ${previous} -> ${rows.length}`);

const body = rows.map(r => JSON.stringify(r)).join(',\n');
writeFileSync(out, `// Generated by scripts/update-draws.mjs. Do not edit by hand.\n// [draw, date, n1, n2, n3, n4, n5, n6, bonus, firstPrize, firstWinners]\nwindow.DRAWS = [\n${body}\n];\n`);
console.log(`www/draws.js: ${rows.length} draws (latest ${rows.at(-1)[0]}, ${rows.at(-1)[1]})`);
